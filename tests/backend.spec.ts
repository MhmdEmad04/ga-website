import { expect,test } from '@playwright/test';
const origin='http://127.0.0.1:3001';
test('admin is protected and cross-origin mutations are rejected',async({page,request})=>{
  await page.goto('/admin');await expect(page).toHaveURL(/\/admin\/login$/);
  const unauthorized=await request.post('/api/admin/products',{headers:{Origin:origin},data:{}});expect(unauthorized.status()).toBe(401);
  const unauthorizedRetry=await request.post('/api/admin/notifications',{headers:{Origin:origin},data:{}});expect(unauthorizedRetry.status()).toBe(401);
  const forbidden=await request.post('/api/orders',{headers:{Origin:'https://untrusted.example'},data:{}});expect(forbidden.status()).toBe(403);
  const privateList=await request.get('/api/admin/orders');expect(privateList.status()).toBe(405);
});

